// node tests/holiday.test.js —— 法定节假日数据、调休、排程避让
const C = require('../core.js'); require('../holiday.js'); require('../parse.js'); require('../sched.js');
const H = C.Holiday, assert = require('assert'); let n = 0; const ok = (c, m) => { assert(c, m); n++; console.log('  ✓ ' + m); };
const d = (y, m, dd) => new Date(y, m - 1, dd).getTime();
console.log('2026 年(国务院办公厅 2025-11 通知)');
ok(H.info(d(2026, 10, 1)).kind === 'holiday' && H.info(d(2026, 10, 1)).name === '国庆节', '10/1 国庆节放假');
ok(H.info(d(2026, 10, 7)).kind === 'holiday' && H.info(d(2026, 10, 8)).kind === 'work', '10/7 仍放假,10/8 恢复上班');
ok(H.info(d(2026, 9, 20)).kind === 'makeup' && H.info(d(2026, 10, 10)).kind === 'makeup', '9/20(周日)、10/10(周六)调休上班');
ok(H.info(d(2026, 2, 14)).kind === 'makeup' && H.info(d(2026, 2, 28)).kind === 'makeup' && H.info(d(2026, 2, 15)).kind === 'holiday' && H.info(d(2026, 2, 23)).kind === 'holiday', '春节 2/15–2/23 放假,2/14、2/28 补班');
ok(H.info(d(2026, 9, 25)).name === '中秋节' && H.info(d(2026, 9, 27)).kind === 'holiday', '中秋 9/25–9/27');
ok(H.info(d(2026, 11, 13)).kind === 'work' && H.info(d(2026, 11, 14)).kind === 'weekend', '普通日:周五工作日、周六周末');
console.log('2027 年(国办发明电〔2026〕10 号,2026-11-05)');
ok(H.info(d(2027, 2, 5)).kind === 'holiday' && H.info(d(2027, 2, 13)).kind === 'holiday' && H.info(d(2027, 2, 4)).kind === 'work', '春节 2/5(除夕)–2/13 共 9 天');
ok(H.info(d(2027, 1, 31)).kind === 'makeup' && H.info(d(2027, 2, 14)).kind === 'makeup', '1/31、2/14(周日)上班');
ok(H.info(d(2027, 6, 9)).kind === 'holiday' && H.info(d(2027, 6, 8)).kind === 'work', '端午 6/9 一天');
ok(H.info(d(2027, 9, 15)).name === '中秋节' && H.info(d(2027, 9, 26)).kind === 'makeup' && H.info(d(2027, 10, 9)).kind === 'makeup', '中秋 9/15;国庆前后补班 9/26、10/9');
let off = 0; for (let t = d(2027, 10, 1); t <= d(2027, 10, 7); t += 86400000) if (H.info(t).kind === 'holiday') off++; ok(off === 7, '国庆 7 天');
let sp = 0; for (let t = d(2027, 2, 5); t <= d(2027, 2, 13); t += 86400000) if (H.info(t).kind === 'holiday') sp++; ok(sp === 9, '春节 9 天');
console.log('标签与其他');
ok(H.tag(d(2026, 10, 3)).text === '休' && H.tag(d(2026, 10, 10)).text === '班' && H.tag(d(2026, 11, 13)) === null, '界面标签:休 / 班 / 无');
ok(H.isRest(d(2026, 10, 10)) === false && H.isRest(d(2026, 10, 4)) === true, '补班的周六不算休息日');
ok(H.info(d(2028, 1, 1)).est === true && H.info(d(2028, 5, 1)).kind === 'holiday' && H.info(d(2028, 3, 6)).kind === 'work', '无官方数据的年份:只预估元旦/劳动节/国庆,并标「预估」');
const up = H.upcoming(d(2026, 9, 18), 30); ok(up.some((s) => s.name === '中秋节') && up.some((s) => s.name === '国庆节' && s.kind === 'holiday'), '未来 30 天的假期段');
console.log('排程');
const now = d(2026, 9, 28) + 8 * 3600e3;
const st = C.fresh();
const t = C.addItems(st, C.parse('十月八号前写方案,三个小时', st, now).items, now)[0]; C.plan(st, now, 'inc');
const days = st.blocks.filter((b) => b.itemId === t.id && !b.skipped).map((b) => new Date(b.start).getDate());
ok(days.length >= 2 && days.every((x) => !(x >= 1 && x <= 7 && new Date(st.blocks[0].start).getMonth() === 9) ), '工作任务避开国庆 10/1–10/7:' + days.join(','));
const st2 = C.fresh(); st2.settings.holidayAvoid = false; st2.settings.freeRatio = 0.1;
ok(C.dayKind(d(2026, 10, 10)) === 'makeup' && C.isRestDay(d(2026, 10, 10)) === false, '补班日按工作日(通勤等按工作日)');
st2.settings.commute.on = true; ok(C.commuteOn(st2.settings, d(2026, 10, 10)) === true && C.commuteOn(st2.settings, d(2026, 10, 3)) === false, '通勤:补班日有,放假日没有');
console.log('\n节假日测试通过:' + n);
